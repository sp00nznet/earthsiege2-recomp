#!/usr/bin/env python3
"""Lift VSHELL.EXE and DBSIM.EXE to C in src/recomp/gen/{shell,sim}/.

Two executables, both based at 0x00400000: each becomes its own host
(es2shell.exe, es2sim.exe), the way ES.EXE spawned them as two processes.
The loop is pcrecomp's shared `tools/lift/drive32.py`.

    py -3 tools/catalog.py
    py -3 run_lift.py [shell|sim]
"""
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.join(os.environ.get('PCRECOMP', os.path.join(HERE, '..', 'pcrecomp')), 'tools')
sys.path[:0] = [os.path.join(TOOLS, 'lift'), os.path.join(TOOLS, 'pe')]
from drive32 import lift_image  # noqa: E402

WORK = os.path.join(HERE, 'work')
MODULES = {'shell': 'VSHELL.EXE', 'sim': 'DBSIM.EXE'}


def put(path, text):
    """Write only a change, so an unchanged header does not rebuild every chunk."""
    if not os.path.exists(path) or open(path, newline='').read() != text:
        with open(path, 'w', newline='\n') as f:
            f.write(text)


def lift(mod):
    t0 = time.time()
    cat = os.path.join(WORK, mod + '.functions.json')
    if not os.path.exists(cat):
        sys.exit('no catalog -- run `py -3 tools/catalog.py` first')
    seeds_p = os.path.join(WORK, mod + '.seeds.json')
    seeds = json.load(open(seeds_p)) if os.path.exists(seeds_p) else []
    out = os.path.join(HERE, 'src', 'recomp', 'gen', mod)
    os.makedirs(out, exist_ok=True)
    st, entries = lift_image(os.path.join(HERE, 'game', MODULES[mod]), cat, os.path.join(out, 'm'), seeds=seeds)
    json.dump(st, open(os.path.join(WORK, mod + '.lift_stats.json'), 'w'), indent=1)
    put(os.path.join(out, 'recomp_funcs.h'),
        '/* AUTO-GENERATED by run_lift.py */\n#pragma once\n#include <stdint.h>\n\n'
        + ''.join('void sub_%08X(void);\n' % a for a in entries))
    put(os.path.join(out, 'recomp_dispatch.c'),
        '/* AUTO-GENERATED by run_lift.py */\n#include "recomp_types.h"\n#include "recomp_funcs.h"\n\n'
        'const recomp_dispatch_entry_t recomp_dispatch_table[] = {\n'
        + ''.join('    { 0x%08Xu, sub_%08X },\n' % (a, a) for a in entries)
        + '};\nconst uint32_t recomp_dispatch_count = %d;\n' % len(entries))
    print('  %s: %d functions, lift errors %d, unimplemented instructions %d, %.0fs'
          % (mod, len(entries), st['errors'], sum(st['unimplemented'].values()), time.time() - t0))


if __name__ == '__main__':
    for m in sys.argv[1:] or MODULES:
        lift(m)
